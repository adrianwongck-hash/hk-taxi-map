function edge(
  from: string,
  to: string,
  lengthM: number,
  nameEn: string,
  nameZh: string,
  tollHkd?: number,
  flags?: ("tunnel" | "bridge" | "restricted")[],
) {
  return {
    id: `${from}-${to}`,
    from,
    to,
    lengthM,
    nameEn,
    nameZh,
    taxiTypes: ["red" as const],
    ...(tollHkd !== undefined ? { tollHkd } : {}),
    ...(flags ? { flags } : {}),
  };
}

function lm(nodeId: string, nameEn: string, nameZh: string) {
  return {
    id: `lm-${nodeId}`,
    nodeId,
    nameEn,
    nameZh,
    taxiTypes: ["red" as const],
  };
}
